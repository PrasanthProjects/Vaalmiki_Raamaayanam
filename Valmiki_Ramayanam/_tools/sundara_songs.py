def shared():
    meta = {}
    for line in FIRST.read_text(encoding='utf-8').split('\n---\n', 1)[0].splitlines():
        k, _, v = line.partition(': ')
        if k in SHARED:
            meta[k] = v
    return meta


def write(song, meta):
    head = [f"NO: {song['no']}", f"TITLE: {song['title']}", 'KANDA: 5_Sundara_Kanda', f"SARGA: {song['sarga']}",
            f"SLOKAS: {song['slokas']}", 'LENGTH: 5:00', f"GIST: {song['gist']}",
            *(f'{k}: {meta[k]}' for k in ('RAGA', 'TALA', 'BPM')), f"MOOD: {song['mood']}",
            *(f'{k}: {meta[k]}' for k in ('VOICES', 'VOICE', 'INSTRUMENTS', 'STYLE', 'EXCLUDE'))]
    head += [f'SOURCE: {a} | సుందరకాండ {b} | {c}' if b[0].isdigit() else f'SOURCE: {a} | సుందరకాండ {b} | {c}'
             for a, b, c in song['sources']]
    head.append(f"THUMBPIC: {song['thumb'][0]} | {song['thumb'][1]} | {song['thumb'][2]}")
    head += [f'SCENE: {a} | {k} | {f} | {l}' for a, k, f, l in song['scenes']]
    lyr = song['lyrics'].strip()
    assert lyr.count(PALLAVI) == 1 and lyr.count('[శ్లోక గానం') == 3 and lyr.count('[చరణం') == 4, song['no']
    for block in lyr.split('\n\n'):
        if block.startswith('[చరణం'):
            assert len(block.splitlines()) == 9, (song['no'], block[:40])
    out = SONGS_DIR / f"sundara_sarga_{song['sarga']:03d}_song.txt"
    out.write_text('\n'.join(head) + '\n---\n' + lyr + '\n', encoding='utf-8', newline='\n')
    return out, len(lyr)


if __name__ == '__main__':
    m = shared()
    for s in SONGS:
        p, n = write(s, m)
        print(p.name, s['title'], n, 'chars')
